// Katalogdagi {uz, ru, en} ko'rinishidagi nomlardan joriy tilni tanlaydi.
export function pick(obj, lang) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[lang] || obj.uz || obj.ru || obj.en || '';
}
